package com.networknt.encryptor;

import org.junit.jupiter.api.Test;

import javax.crypto.Cipher;
import javax.crypto.SecretKeyFactory;
import javax.crypto.spec.GCMParameterSpec;
import javax.crypto.spec.PBEKeySpec;
import javax.crypto.spec.SecretKeySpec;
import java.io.ByteArrayOutputStream;
import java.io.Console;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.util.HexFormat;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

class LegacyCryptMigratorTest {
    // Generated by the historical encryptor at 22028d1, not by migration code.
    private static final String LEGACY = "CRYPT:fc26c8416655560dc367b0636129d491:133bb376708628cc915ee9882603606d";
    private static final String EMPTY = "CRYPT:c1eaeefae703df2417d1ef5c5cc74b60:d28023c32d45ad33bc3987cbb823037d";
    private static final String PASSWORD = "migration-test-key";

    @Test
    void migratesHistoricalUnicodeAndEmptyValues() throws Exception {
        char[] key = PASSWORD.toCharArray();
        String migrated = LegacyCryptMigrator.migrate(LEGACY, key, key);
        assertEquals("secret-ü-🔑", decrypt(migrated, key));
        assertEquals("", decrypt(LegacyCryptMigrator.migrate(EMPTY, key, key), key));
        assertArrayEquals(PASSWORD.toCharArray(), key);
        String[] parts = migrated.split(":");
        assertEquals(4, parts.length);
        assertEquals(32, parts[1].length());
        assertEquals(24, parts[2].length());
    }

    @Test
    void rotatesKeyAndGeneratesFreshSaltAndNonce() throws Exception {
        char[] oldKey = PASSWORD.toCharArray();
        char[] newKey = "new-migration-test-key".toCharArray();
        String first = LegacyCryptMigrator.migrate(LEGACY, oldKey, newKey);
        String second = LegacyCryptMigrator.migrate(LEGACY, oldKey, newKey);
        assertEquals("secret-ü-🔑", decrypt(first, newKey));
        assertThrows(GeneralSecurityException.class, () -> decrypt(first, oldKey));
        assertNotEquals(first.split(":")[1], second.split(":")[1]);
        assertNotEquals(first.split(":")[2], second.split(":")[2]);
        char last = first.charAt(first.length() - 1);
        String tampered = first.substring(0, first.length() - 1) + (last == '0' ? '1' : '0');
        assertThrows(GeneralSecurityException.class, () -> decrypt(tampered, newKey));
        assertArrayEquals("new-migration-test-key".toCharArray(), newKey);
    }

    @Test
    void rejectsMalformedInputsAndBlankKeys() {
        char[] key = PASSWORD.toCharArray();
        String salt = "00".repeat(16);
        for (String input : new String[]{null, "", "CRYPT::00", "OTHER:" + salt + ":" + salt,
                "CRYPT:" + salt + ":", "CRYPT:" + salt + ":0", "CRYPT:" + salt + ":" + "zz".repeat(16),
                "CRYPT:" + "gg".repeat(16) + ":" + salt, "CRYPT:" + salt + ":" + salt + ":" + salt}) {
            assertThrows(IllegalArgumentException.class, () -> LegacyCryptMigrator.migrate(input, key, key));
        }
        for (char[] blank : new char[][]{null, new char[0], " \t".toCharArray()}) {
            assertThrows(IllegalArgumentException.class, () -> LegacyCryptMigrator.migrate(LEGACY, blank, key));
            assertThrows(IllegalArgumentException.class, () -> LegacyCryptMigrator.migrate(LEGACY, key, blank));
        }
        // This fixture fails padding with this key; CBC cannot detect every wrong key.
        assertThrows(GeneralSecurityException.class,
                () -> LegacyCryptMigrator.migrate(LEGACY, "wrong-key".toCharArray(), key));
    }

    @Test
    void interactiveMigrationEmitsOnlyCiphertextAndClearsPromptBuffers() throws Exception {
        Console console = mock(Console.class);
        char[] input = LEGACY.toCharArray();
        char[] key = PASSWORD.toCharArray();
        char[] newKey = "rotated-key".toCharArray();
        char[] confirm = newKey.clone();
        when(console.readPassword("Legacy CRYPT value (hidden): ")).thenReturn(input);
        when(console.readPassword("Original master key: ")).thenReturn(key);
        when(console.readPassword("New master key: ")).thenReturn(newKey);
        when(console.readPassword("Confirm new master key: ")).thenReturn(confirm);
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        assertEquals(0, LegacyCryptMigrator.run(console, new PrintStream(out), new PrintStream(err), true));
        assertEquals("secret-ü-🔑", decrypt(out.toString(StandardCharsets.UTF_8).strip(), "rotated-key".toCharArray()));
        assertArrayEquals(new char[input.length], input);
        assertArrayEquals(new char[key.length], key);
        assertArrayEquals(new char[newKey.length], newKey);
        assertArrayEquals(new char[confirm.length], confirm);
        assertFalse(err.toString(StandardCharsets.UTF_8).contains(PASSWORD));
    }

    @Test
    void failuresEmitNoReplacement() {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        PrintStream sink = new PrintStream(new ByteArrayOutputStream());
        assertEquals(1, LegacyCryptMigrator.run(null, new PrintStream(out), sink, false));
        Console console = mock(Console.class);
        when(console.readPassword("Legacy CRYPT value (hidden): ")).thenReturn(LEGACY.toCharArray());
        when(console.readPassword("Original master key: ")).thenReturn(PASSWORD.toCharArray());
        when(console.readPassword("New master key: ")).thenReturn("one".toCharArray());
        when(console.readPassword("Confirm new master key: ")).thenReturn("two".toCharArray());
        assertEquals(1, LegacyCryptMigrator.run(console, new PrintStream(out), sink, true));
        when(console.readPassword("Legacy CRYPT value (hidden): ")).thenReturn("invalid".toCharArray());
        assertEquals(1, LegacyCryptMigrator.run(console, new PrintStream(out), sink, false));
        when(console.readPassword("Legacy CRYPT value (hidden): ")).thenReturn((char[]) null);
        assertEquals(1, LegacyCryptMigrator.run(console, new PrintStream(out), sink, false));
        assertEquals("", out.toString(StandardCharsets.UTF_8));
    }

    @Test
    void interactiveMigrationRetainsOriginalKeyByDefault() throws Exception {
        Console console = mock(Console.class);
        when(console.readPassword("Legacy CRYPT value (hidden): ")).thenReturn(LEGACY.toCharArray());
        when(console.readPassword("Original master key: ")).thenReturn(PASSWORD.toCharArray());
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        assertEquals(0, LegacyCryptMigrator.run(console, new PrintStream(out),
                new PrintStream(new ByteArrayOutputStream()), false));
        assertEquals("secret-ü-🔑", decrypt(out.toString(StandardCharsets.UTF_8).strip(), PASSWORD.toCharArray()));
        verify(console, never()).readPassword("New master key: ");
    }

    private static String decrypt(String value, char[] password) throws Exception {
        String[] parts = value.split(":");
        HexFormat hex = HexFormat.of();
        PBEKeySpec spec = new PBEKeySpec(password, hex.parseHex(parts[1]), 65536, 256);
        try {
            SecretKeySpec key = new SecretKeySpec(SecretKeyFactory.getInstance("PBKDF2WithHmacSHA256")
                    .generateSecret(spec).getEncoded(), "AES");
            Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
            cipher.init(Cipher.DECRYPT_MODE, key, new GCMParameterSpec(128, hex.parseHex(parts[2])));
            return new String(cipher.doFinal(hex.parseHex(parts[3])), StandardCharsets.UTF_8);
        } finally {
            spec.clearPassword();
        }
    }
}
